local function female_surname(surname)
	local endings = {
		{ "ов", "ова" }, { "ев", "ева" }, { "ёв", "ёва" }, { "ин", "ина" }, { "ын", "ына" },
		{ "ий", "ая" }, { "ый", "ая" }, { "ой", "ая" }, { "ской", "ская" }, { "ский", "ская" },
	}
	for _, pair in ipairs(endings) do
		local from, to = pair[1], pair[2]
		if #surname >= #from and surname:sub(-#from) == from then
			return surname:sub(1, #surname - #from) .. to
		end
	end
	return surname
end

-- Возвращает полную личность: имя, пол, фамилию и возраст.
function N.identity(rng)
	local female = rng(0, 1) == 1
	local first = female and N.female_first[rng(1, #N.female_first)]
		or N.male_first[rng(1, #N.male_first)]
	local surname = N.surnames[rng(1, #N.surnames)]
	if female then surname = female_surname(surname) end
	return {
		name = first,
		full_name = first .. " " .. surname,
		gender = female and "female" or "male",
		age = N.ages[rng(1, #N.ages)],
	}
end

